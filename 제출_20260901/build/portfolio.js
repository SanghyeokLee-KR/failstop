// 본문 문단. runs 는 문자열 또는 {t, b(굵게), c(색), mono, sz} 배열
function P(runs, { spaceBefore = 0, spaceAfter = 120, align, indent } = {}) {
  const arr = (Array.isArray(runs) ? runs : [runs]).map((r) => {
    if (typeof r === 'string') r = { t: r }
    return new TextRun({
      text: r.t, bold: !!r.b, color: r.c || BODY,
      font: r.mono ? MONO : KO, size: r.sz || 20,
    })
  })
  return new Paragraph({
    children: arr, alignment: align,
    spacing: { before: spaceBefore, after: spaceAfter, line: 288 },
    indent: indent ? { left: indent } : undefined,
  })
}

function H1(text, { pageBreak = false } = {}) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1, pageBreakBefore: pageBreak,
    spacing: { before: 320, after: 160 },
    children: [new TextRun({ text, bold: true, color: INK, font: KO, size: 30 })],
  })
}
function H2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 240, after: 100 },
    children: [new TextRun({ text, bold: true, color: INK, font: KO, size: 23 })],
  })
}
function H3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 160, after: 80 },
    children: [new TextRun({ text, bold: true, color: BODY, font: KO, size: 20 })],
  })
}

// 고정폭 블록. ASCII 도식과 판별 트리에 쓴다. 이미지로 바꾸지 않는 이유는
// 원문 판단 논리를 글자 그대로 보존하고 검색 가능하게 두기 위해서다.
function MONO_BLOCK(lines, size = 15) {
  return lines.map((l, i) => new Paragraph({
    spacing: { before: 0, after: i === lines.length - 1 ? 140 : 0, line: 240 },
    shading: { type: ShadingType.CLEAR, fill: 'FAFBFC' },
    children: [new TextRun({ text: l.length ? l : ' ', font: MONO, size, color: INK })],
  }))
}

const thin = { style: BorderStyle.SINGLE, size: 4, color: LINE }
const CELL_BORDERS = { top: thin, bottom: thin, left: thin, right: thin }

// 표. headers 문자열 배열, rows 는 (문자열 | {t,b,c}) 2차원, widths 는 DXA 합계 = total
function T(headers, rows, widths, { total = TW, size = 18, headerRepeat = true } = {}) {
  const mk = (v, isHead) => {
    if (typeof v === 'string') v = { t: v }
    return new Paragraph({
      spacing: { before: 20, after: 20, line: 252 },
      children: [new TextRun({
        text: v.t, bold: isHead || !!v.b, font: KO, size,
        color: v.c || (isHead ? INK : BODY),
      })],
    })
  }
  const row = (cells, isHead) => new TableRow({
    tableHeader: isHead && headerRepeat,
    children: cells.map((v, i) => new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      borders: CELL_BORDERS, verticalAlign: VerticalAlign.CENTER,
      shading: isHead ? { type: ShadingType.CLEAR, fill: HEADFILL } : undefined,
      margins: { top: 40, bottom: 40, left: 80, right: 80 },
      children: [mk(v, isHead)],
    })),
  })
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    rows: [row(headers, true), ...rows.map((r) => row(r, false))],
  })
}

function GAP(h = 120) { return new Paragraph({ spacing: { before: 0, after: h }, children: [] }) }

function NOTE(text) {
  return new Paragraph({
    spacing: { before: 60, after: 140, line: 264 },
    children: [new TextRun({ text, font: KO, size: 17, color: MUTE })],
  })
}

function IMG(file, w, h) {
  return new Paragraph({
    alignment: AlignmentType.CENTER, spacing: { before: 60, after: 60 },
    children: [new ImageRun({
      type: 'png', data: fs.readFileSync(path.join(__dirname, '..', 'diagram', file)),
      transformation: { width: w, height: h },
    })],
  })
}

