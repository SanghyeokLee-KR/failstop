/**
 * 목록 한 쪽의 크기. 화면마다 흩어져 있던 상수를 한곳에 모은다.
 *
 * 흩어져 있을 때의 문제는 값이 다르다는 것 자체가 아니라 왜 다른지가 어디에도 없다는 것이다.
 * 50·50·50·20·200이 각자의 파일에 있었고, 한 화면을 고칠 때 다른 화면의 근거를 알 수 없었다.
 */

/**
 * 처리 큐 한 쪽. 출금·문의·신고·회원·공지가 쓴다.
 *
 * 종전 50에서 줄였다. 50행이면 표 높이가 2,000px를 넘어 쪽 이동 버튼이 화면 밖에 있었고,
 * 쪽을 넘기려면 먼저 스크롤을 끝까지 내려야 했다. 볼 수 없는 쪽은 쪽이 아니다.
 * 이 목록들은 주기 폴링 없이 진입·조건 변경·조작 뒤에만 읽으므로 쪽 크기는 화면 높이로 정한다.
 */
export const QUEUE_PAGE_SIZE = 25;

/**
 * 감사 로그 한 쪽. 훑어 읽는 표라 크게 잡는다. 서버 상한은 500이다.
 *
 * 다른 목록과 값이 다른 이유가 있다. 이 화면의 운영자·액션·결과 필터는 서버가 받지 않아
 * 불러온 쪽 안에서만 거른다. 쪽을 줄이면 거르는 범위가 함께 줄어 필터가 더 좁은 거짓말을
 * 하게 된다. 화면은 "표시 N건 · 불러온 M건 기준"으로 그 범위를 상시 고지한다.
 * 갱신도 수동이라 큰 쪽의 비용이 주기적으로 나가지 않는다.
 */
export const AUDIT_PAGE_SIZE = 200;

/**
 * 처리 대기 카드가 세는 상한. 이 수를 채우면 화면이 "25+"로 적는다.
 *
 * 정확한 총계를 내려면 서버에 개수 API가 있어야 한다. 없는 값을 첫 쪽 길이로 대신하면
 * 대기가 상한을 넘은 순간부터 카드가 조용히 같은 수를 계속 띄운다.
 */
export const QUEUE_COUNT_CAP = QUEUE_PAGE_SIZE;

/** 상한을 채운 개수를 적는다. 채웠으면 그 이상이라는 사실을 숨기지 않는다 */
export function countLabel(loaded: number, hasMore: boolean): string {
  return hasMore ? `${loaded}+` : String(loaded);
}
