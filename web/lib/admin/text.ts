/**
 * 관리 콘솔 글자의 줄바꿈 자리(디자인 시스템 §12-12). 가운뎃점으로 이은 글('조회 ASG · 평균 74%')은 가운뎃점 앞
 * 공백을 줄바꿈하지 않는 공백(U+00A0)으로 바꿔 줄이 가운뎃점으로 시작하지 않게 한다. 뒤 공백은 그대로라 줄은
 * 가운뎃점 뒤에서 바뀐다. 시뮬레이터와 상담 규칙이 만든 문장은 시험이 보는 원문이라 그리는 자리에서 바꾼다
 */
export function joinDots(text: string): string {
  return text.replace(/ ·/g, "\u00a0·");
}
