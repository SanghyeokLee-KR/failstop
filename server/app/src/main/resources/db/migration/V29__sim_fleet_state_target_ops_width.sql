-- sim_fleet_state.target_ops 폭 확대. V28 이 NUMERIC(12,3) 으로 잡아 절댓값 10^9 이상을 담지 못한다.
--
-- 왜 별도 마이그레이션인가. V28 이 이미 적용된 DB 가 있어 그 파일을 고치면 Flyway 체크섬이
-- 어긋나 전 노드가 기동하지 않는다. 적용된 마이그레이션은 수정하지 않는다.
--
-- 왜 필요한가. API §6-A 가 OPS 에 상한을 두지 않기로 규정하고 PUT /sim/rate 의 parsePositive 는
-- 유한한 양수를 전부 통과시킨다. 10^9 이상을 설정하면 발행이 매초 numeric field overflow 로
-- 실패하는데, 발행 실패는 warn 로그로만 남으므로 관리 콘솔에는 "발행 끊김" 으로 보인다.
-- 살아 있는 봇 노드를 죽은 것으로 오진하게 된다. 상한을 두지 않기로 한 계약 쪽을 따라 폭을 넓힌다.
--
-- 소수 6자리로 올리는 이유. 거버너 원값이 double 이고 로컬 경로는 String.valueOf(double) 로
-- 전 자릿수를 낸다. 3자리에서는 8.3333 이 발행 경로에서만 8.333 이 되어 두 원천의 값이 갈린다.
-- 6자리가 배수 프리셋(x1.5·x2·x10·x12)이 만드는 값을 모두 담는다.
ALTER TABLE sim_fleet_state ALTER COLUMN target_ops TYPE NUMERIC(20,6);
